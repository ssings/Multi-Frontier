def now_text() -> str:
    return datetime.now().astimezone().isoformat(timespec="seconds")


def read_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8-sig")
    except UnicodeDecodeError:
        return path.read_text(encoding="gb18030")


def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def decode_process_output(data: bytes | None) -> str:
    if not data:
        return ""
    for encoding in ("utf-8", "gb18030", sys.getdefaultencoding()):
        try:
            return data.decode(encoding)
        except UnicodeDecodeError:
            continue
    return data.decode("utf-8", errors="replace")


def choose_existing(paths: Sequence[Path]) -> Path:
    for path in paths:
        if path.is_file():
            return path
    raise FileNotFoundError(
        "Required reference files not found; checked:\n" + "\n".join(str(p) for p in paths)
    )


def parse_key_value_file(path: Path) -> Dict[str, str]:
    values: Dict[str, str] = {}
    for line in read_text(path).splitlines():
        if "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip()
    return values


def find_pending_stage1_run() -> Tuple[Path, int, Dict[str, str]]:
    """
    Select the earliest successfully generated number from output2/stage1 that has not yet been used by the current experiment group.

    For example:
        output2/stage1/01 as the unified input;
        T1 outputs to output2/t1/01;
        T2 outputs to output2/t2/01;
        T3 outputs to output2/t3/01.

    The three groups can independently use the same Stage 1 number, ensuring input consistency.
    """
    STAGE1_ROOT.mkdir(parents=True, exist_ok=True)
    GROUP_DIR.mkdir(parents=True, exist_ok=True)

    candidates: List[Tuple[Path, int, Dict[str, str]]] = []

    for stage1_run in sorted(
        (
            path
            for path in STAGE1_ROOT.iterdir()
            if path.is_dir()
            and re.fullmatch(r"\d{2,}", path.name)
        ),
        key=lambda path: int(path.name),
    ):
        repeat_index = int(stage1_run.name)
        stage1_result = stage1_run / "result.txt"
        stage1_spec = stage1_run / "Cassandra_Specification.md"
        stage1_docs = stage1_run / "cassandra_official_docs.md"

        if not all(
            path.is_file()
            for path in (
                stage1_result,
                stage1_spec,
                stage1_docs,
            )
        ):
            continue

        values = parse_key_value_file(stage1_result)
        if (
            values.get("docs_result") != "pass"
            or values.get("spec_result") != "pass"
        ):
            continue

        # Stage 2 only reads Stage 1 generated by the same exact model and the same provider.
        if values.get("model") != MODEL:
            continue
        if values.get("provider", PROVIDER) != PROVIDER:
            continue

        group_run = GROUP_DIR / stage1_run.name
        if not group_run.exists():
            candidates.append(
                (stage1_run, repeat_index, values)
            )
            continue

        if not (group_run / "result.txt").is_file():
            raise FileExistsError(
                f"Experiment directory already exists but has no result.txt: {group_run}."
                "To avoid overwriting, please handle this directory manually first."
            )

    if not candidates:
        raise FileNotFoundError(
            f"No successful Stage 1 under {STAGE1_ROOT} generated by the current model {MODEL},"
            f"and not yet used by {EXPERIMENT_GROUP.upper()} was found."
            "Please run the Cassandra Stage 1 script under output2/stage1 first."
        )

    return candidates[0]

def prepare_run() -> Tuple[Path, Path, Dict[str, str], int]:
    global RUN_DIR, CASSANDRA_DIR, ERROR_DIR
    global RESULT_PATH, HARD_CHECK_LOG_PATH, TLC_LOG_PATH
    global STAGE1_SPEC_PATH, STAGE1_DOCS_PATH

    stage1_run, repeat_index, stage1_values = (
        find_pending_stage1_run()
    )

    GROUP_DIR.mkdir(parents=True, exist_ok=True)
    run_dir = GROUP_DIR / f"{repeat_index:02d}"
    run_dir.mkdir(parents=False, exist_ok=False)

    RUN_DIR = run_dir
    CASSANDRA_DIR = RUN_DIR / "Cassandra"
    CASSANDRA_DIR.mkdir(parents=True, exist_ok=False)
    RESULT_PATH = RUN_DIR / "result.txt"
    HARD_CHECK_LOG_PATH = RUN_DIR / "hard_check_report.txt"
    TLC_LOG_PATH = RUN_DIR / "tlc_output.txt"
    ERROR_DIR = RUN_DIR / "error"
    STAGE1_SPEC_PATH = stage1_run / "Cassandra_Specification.md"
    STAGE1_DOCS_PATH = (
        stage1_run / "cassandra_official_docs.md"
    )

    return RUN_DIR, stage1_run, stage1_values, repeat_index

