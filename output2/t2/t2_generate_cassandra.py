def _usage_from_chat(response) -> Dict[str, int]:
    usage = getattr(response, "usage", None)
    return {
        "prompt_tokens": int(getattr(usage, "prompt_tokens", 0) or 0),
        "completion_tokens": int(
            getattr(usage, "completion_tokens", 0) or 0
        ),
        "total_tokens": int(getattr(usage, "total_tokens", 0) or 0),
    }


def call_model(
    client: OpenAI,
    prompt: str,
    system_prompt: str,
) -> Tuple[str, Dict[str, int]]:
    last_error: Exception | None = None

    for attempt in range(1, API_RETRIES + 1):
        try:
            kwargs = {
                "model": MODEL,
                "messages": [
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": prompt},
                ],
                "stream": False,
                "max_tokens": MAX_OUTPUT_TOKENS,
            }

            response = client.chat.completions.create(
                **kwargs,
                extra_body={"thinking": {"type": "enabled"}},
            )
            content = response.choices[0].message.content or ""
            usage_dict = _usage_from_chat(response)

            if not content.strip():
                raise PipelineError(
                    f"Model ds/{MODEL} returned empty content."
                )
            return content, usage_dict

        except Exception as exc:
            last_error = exc
            if attempt >= API_RETRIES:
                break
            wait_seconds = min(30, 2 ** attempt)
            print(
                f"DeepSeek API call failed"
                f"（{attempt}/{API_RETRIES}）：{exc}"
            )
            time.sleep(wait_seconds)

    raise PipelineError(
        f"model ds/{MODEL} API call ultimately failed: {last_error}"
    )

def add_usage(result: Dict[str, object], usage: Dict[str, int]) -> None:
    result["api_calls"] = int(result["api_calls"]) + 1
    for key in ("prompt_tokens", "completion_tokens", "total_tokens"):
        result[key] = int(result[key]) + int(usage.get(key, 0))


