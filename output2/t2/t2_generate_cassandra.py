def validate_current(
    stage1_values: Dict[str, str],
) -> Tuple[Dict[str, str], Dict[str, str], str, str]:
    """
    The loop phase only handles files, dependencies, cfg, SANY, and TLC issues necessary for execution.

    hard check does not form repair feedback here, but after generation ends or after the repair loop ends
    Evaluated once separately by evaluate_final_hard_check().
    """
    status = new_status(stage1_values)
    reasons: Dict[str, str] = {}

    module_paths, module_texts, graph, tla_errors = (
        analyze_modules()
    )
    status["tla_result"] = (
        "pass" if not tla_errors else "fail"
    )
    if tla_errors:
        reasons["tla_reason"] = "；".join(tla_errors[:8])

    sany_order: List[Path] = []
    structure_errors: List[str] = []
    if not tla_errors:
        sany_order, structure_errors = (
            topological_module_order(
                module_paths,
                graph,
            )
        )

    cfg_errors: List[str] = []
    entry_module: str | None = None
    if not tla_errors and not structure_errors:
        cfg_errors, entry_module = cfg_precheck(
            module_paths,
            module_texts,
            graph,
        )

    if cfg_errors:
        status["cfg_result"] = "fail"
        reasons["cfg_reason"] = "；".join(cfg_errors[:8])
    elif cfg_path().is_file() and not tla_errors:
        status["cfg_result"] = "pass"

    if tla_errors:
        return (
            status,
            reasons,
            "tla",
            "\n".join(tla_errors),
        )

    if structure_errors:
        return (
            status,
            reasons,
            "structure",
            "\n".join(structure_errors),
        )

    if cfg_errors or entry_module is None:
        return (
            status,
            reasons,
            "cfg",
            "\n".join(cfg_errors)
            or "Unable to uniquely determine the entry module of Cassandra.cfg",
        )

    sany_ok, sany_output = run_sany(sany_order)
    status["sany_result"] = (
        "pass" if sany_ok else "fail"
    )
    if not sany_ok:
        reasons["sany_reason"] = concise_sany_reason(
            sany_output
        )
        return (
            status,
            reasons,
            "sany",
            sany_output,
        )

    tlc_ok, cfg_parser_ok, tlc_output, timed_out = (
        run_tlc_smoke(entry_module)
    )
    status["tlc_end"] = (
        "timeout" if timed_out else "completed"
    )

    if not cfg_parser_ok:
        status["cfg_result"] = "fail"
        status["tlc_result"] = "not_run"
        reasons["cfg_reason"] = concise_cfg_reason(
            tlc_output
        )
        return (
            status,
            reasons,
            "cfg",
            tlc_output,
        )

    status["cfg_result"] = "pass"
    status["tlc_result"] = (
        "pass" if tlc_ok else "fail"
    )
    if not tlc_ok:
        reasons["tlc_reason"] = concise_tlc_reason(
            tlc_output
        )
        return (
            status,
            reasons,
            "tlc",
            tlc_output,
        )

    return status, reasons, "success", tlc_output

def evaluate_final_hard_check(
    status: Dict[str, str],
    reasons: Dict[str, str],
) -> None:
    """
    Evaluated only once at the end of a generation or after all repair loops.

    Results are written to result.txt / hard_check_report.txt,
    They are not fed back to the model and will not trigger any additional repairs.
    """
    module_paths, module_texts, graph, tla_errors = (
        analyze_modules()
    )

    sany_order: List[Path] = []
    structure_errors: List[str] = []
    if not tla_errors:
        sany_order, structure_errors = (
            topological_module_order(
                module_paths,
                graph,
            )
        )

    cfg_errors: List[str] = []
    entry_module: str | None = None
    if not tla_errors and not structure_errors:
        cfg_errors, entry_module = cfg_precheck(
            module_paths,
            module_texts,
            graph,
        )

    hard_errors: List[str] = []
    if (
        not tla_errors
        and not structure_errors
        and not cfg_errors
    ):
        hard_errors = hard_check_errors(
            module_texts,
            graph,
            entry_module,
        )

    write_hard_check_report(
        tla_errors,
        structure_errors,
        cfg_errors,
        hard_errors,
        entry_module,
        sany_order,
    )

    all_errors = (
        tla_errors
        + structure_errors
        + cfg_errors
        + hard_errors
    )
    status["hard_check_result"] = (
        "fail" if all_errors else "pass"
    )

    if all_errors:
        reasons["hard_check_reason"] = "；".join(
            all_errors[:8]
        )
    else:
        reasons.pop("hard_check_reason", None)

def current_files_bundle() -> str:
    sections: List[str] = []
    for path in discover_tla_files():
        sections.append(
            f"===== FILE: {path.name} =====\n"
            f"{read_text(path)}\n"
            "===== END FILE ====="
        )
    if cfg_path().is_file():
        sections.append(
            f"===== FILE: {CFG_FILE_NAME} =====\n"
            f"{read_text(cfg_path())}\n"
            "===== END FILE ====="
        )
    return "\n\n".join(sections)[:MAX_BUNDLE_CHARS]


def build_repair_prompt(
    stage: str,
    error_details: str,
) -> str:
    current_names = [
        path.name for path in discover_tla_files()
    ]
    if cfg_path().is_file():
        current_names.append(CFG_FILE_NAME)

    return f"""
Please perform a minimal-scope incremental repair on the current Cassandra model.

[Current failure type]
{stage}

[Fixed repair constraints]
{FIXED_REPAIR_CONTRACT}

[Current file names]
{', '.join(current_names) if current_names else 'There are currently no valid files'}

[Output limits for this round]
- The total number of files modified, added, and deleted is at most {MAX_REPAIR_FILES}.
- You may add .tla files with any legal name.
- Cassandra.cfg may be modified, but a second cfg must not be generated.
- Use the DELETE FILE marker when deleting obsolete TLA+ modules.
- Modified or newly added files must return complete content.
- Do not output explanations.

[Complete error]
{error_details[:MAX_ERROR_PROMPT_CHARS]}

[All current files]
{current_files_bundle()}
""".strip()

def normalize_error_stage(stage: str) -> str:
    aliases = {
        "tla": "tla",
        "structure": "structure",
        "cfg": "cfg",
        "hard_check": "hard",
        "sany": "sany",
        "tlc": "tlc",
        "repair": "repair",
        "api": "api",
        "pipeline": "pipeline",
    }
    normalized = aliases.get(stage.strip().lower(), stage.strip().lower())
    normalized = re.sub(r"[^a-z0-9_]+", "_", normalized).strip("_")
    return normalized or "unknown"


def save_error(index: int, stage: str, details: str) -> Path:
    stage_name = normalize_error_stage(stage)
    error_path = ERROR_DIR / f"err{index:02d}_{stage_name}.txt"
    content = (
        f"time={now_text()}\n"
        f"stage={stage}\n"
        f"model={MODEL}\n"
        f"error_index={index}\n"
        f"\n===== DETAILS =====\n"
        f"{details}\n"
    )
    write_text(error_path, content)
    return error_path

def apply_repair_response(
    response_text: str,
) -> Tuple[bool, str]:
    files, unexpected, duplicates = extract_generated_files(
        response_text,
        allow_cfg=True,
    )
    deletes = extract_delete_requests(response_text)

    problems: List[str] = []
    if unexpected:
        problems.append(
            "Forbidden files returned: " + ", ".join(unexpected)
        )
    if duplicates:
        problems.append(
            "Duplicate files output in the same response: " + ", ".join(duplicates)
        )

    modifications = len(files) + len(deletes)
    if modifications == 0:
        problems.append("The repair response contains no file modification or deletion request.")
    if modifications > MAX_REPAIR_FILES:
        problems.append(
            f"This round involves {modifications} files,"
            f"exceeding the limit {MAX_REPAIR_FILES}."
        )
    if CFG_FILE_NAME in deletes:
        problems.append("Deleting Cassandra.cfg via DELETE FILE is not allowed.")
    if set(files) & set(deletes):
        problems.append(
            "The same file cannot be modified and deleted simultaneously:"
            + ", ".join(sorted(set(files) & set(deletes)))
        )

    if problems:
        return False, "；".join(problems)

    for name in deletes:
        path = CASSANDRA_DIR / name
        if path.is_file():
            path.unlink()

    save_generated_files(files)
    changed = sorted(files)
    removed = sorted(deletes)
    return True, (
        "updated="
        + (",".join(changed) if changed else "none")
        + "; deleted="
        + (",".join(removed) if removed else "none")
    )


