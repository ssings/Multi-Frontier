def print_summary(
    status: Dict[str, str],
    reasons: Dict[str, str],
) -> None:
    labels = (
        ("Official documentation", "docs_result"),
        ("Cassandra specification", "spec_result"),
        ("TLA+ generation", "tla_result"),
        ("cfg generation and format", "cfg_result"),
        ("Hard checks", "hard_check_result"),
        ("SANY compilation", "sany_result"),
        ("TLC one-minute test", "tlc_result"),
        ("Manual logic check", "manual_logic_result"),
    )
    mapping = {
        "pass": "Pass",
        "fail": "Not passed",
        "not_run": "Not executed",
        "pending": "To be checked",
    }

    print("\nResult summary:")
    for label, key in labels:
        value = status.get(key, "not_run")
        print(f"  {label}：{mapping.get(value, value)}")

    if status.get("tlc_result") != "not_run":
        print(f"  TLC end mode: {status.get('tlc_end')}")

    print(f"  Number of generated TLA files: {len(discover_tla_files())}")
    print(f"  Failed items: {collect_failed_checks(status)}")
    for key in (
        "tla_reason",
        "cfg_reason",
        "hard_check_reason",
        "sany_reason",
        "tlc_reason",
        "api_reason",
    ):
        if reasons.get(key):
            print(f"  {key}：{reasons[key]}")


def update_dynamic_metadata(result: Dict[str, object]) -> None:
    result["generated_tla_files"] = ",".join(
        path.name for path in discover_tla_files()
    ) or "none"

    try:
        module_paths, module_texts, graph, tla_errors = analyze_modules()
        if tla_errors or not cfg_path().is_file():
            result["entry_module"] = "unknown"
            return
        cfg_errors, entry_module = cfg_precheck(
            module_paths,
            module_texts,
            graph,
        )
        result["entry_module"] = (
            entry_module
            if entry_module and not cfg_errors
            else "unknown"
        )
    except Exception:
        result["entry_module"] = "unknown"


def run_one_experiment(
    qdrant_spec: Path,
    qdrant_helper: Path | None,
) -> Dict[str, object]:
    run_dir, stage1_run, stage1_values, repeat_index = (
        prepare_run()
    )

    print(
        f"\n=== Cassandra T2/{repeat_index:02d}："
        "No error-prone rules + file/cfg/SANY/TLC iterative repair ==="
    )
    print(f"Experiment directory: {run_dir}")
    print(f"Corresponding stage-one input: {stage1_run}")
    print(f"Actual model: {PROVIDER}/{MODEL}")

    result: Dict[str, object] = {
        "group": "T2",
        "provider": PROVIDER,
        "model": MODEL,
        "base_url": BASE_URL,
        "repeat_index": f"{repeat_index:02d}",
        "check_scheme": "t2_execution_repairs_no_rules_then_final_hard_check_v1",
        "rules_usage": "not_used",
        "rules_sha256": "not_used",
        "repair_usage": "up_to_max_rounds",
        "hard_check_usage": (
            "final_evaluation_only_no_feedback"
        ),
        "started_at": now_text(),
        "stage1_source": (
            f"stage1/{repeat_index:02d}"
        ),
        "stage1_model": stage1_values.get(
            "model",
            "unknown",
        ),
        "stage1_provider": stage1_values.get(
            "provider",
            "unknown",
        ),
        "stage1_model_match": (
            "true"
            if (
                stage1_values.get("model") == MODEL
                and stage1_values.get(
                    "provider",
                    PROVIDER,
                ) == PROVIDER
            )
            else "false"
        ),
        "spec_sha256": sha256_file(
            STAGE1_SPEC_PATH
        ),
        "docs_sha256": sha256_file(
            STAGE1_DOCS_PATH
        ),
        "initial_tla_calls": 0,
        "initial_cfg_calls": 0,
        "repair_rounds": 0,
        "max_repair_rounds": MAX_REPAIR_ROUNDS,
        "api_calls": 0,
        "prompt_tokens": 0,
        "completion_tokens": 0,
        "total_tokens": 0,
        "stop_reason": "none",
    }

    status = new_status(stage1_values)
    reasons: Dict[str, str] = {}
    client = create_client()
    reference_bundle = build_reference_bundle(
        qdrant_spec,
        qdrant_helper,
    )
    cfg_initial_called = False
    error_index = 0
    stage = "initial"
    details = ""

    try:
        print(
            "Calling the model to autonomously design the Cassandra TLA+ module..."
        )
        response, usage = call_model(
            client,
            build_tla_prompt(reference_bundle),
            "You are a strict TLA+ formal modeling engineer."
            "Initial generation should preserve Cassandra specification semantics."
            "This group does not provide additional error-prone rules;"
            "During repair, only handle current file, cfg, SANY or TLC errors.",
        )
        add_usage(result, usage)
        result["initial_tla_calls"] = 1

        tla_files, unexpected, duplicates = (
            extract_generated_files(
                response,
                allow_cfg=False,
            )
        )
        save_generated_files(tla_files)

        initial_tla_problems: List[str] = []
        if unexpected:
            initial_tla_problems.append(
                "Initial TLA response contains forbidden file:"
                + ", ".join(unexpected)
            )
        if duplicates:
            initial_tla_problems.append(
                "Initial TLA response contains duplicate file:"
                + ", ".join(duplicates)
            )
        if initial_tla_problems:
            reasons["tla_reason"] = "；".join(
                initial_tla_problems
            )

        if discover_tla_files():
            print(
                "Generate Cassandra.cfg for the first time based on actual modules..."
            )
            response, usage = call_model(
                client,
                build_cfg_prompt(reference_bundle),
                "You are a strict TLC configuration engineer."
                "Generate the only runnable Cassandra.cfg based on the current Cassandra TLA+ file.",
            )
            add_usage(result, usage)
            result["initial_cfg_calls"] = 1
            cfg_initial_called = True

            cfg_files, unexpected, duplicates = (
                extract_generated_files(
                    response,
                    allow_cfg=True,
                )
            )
            save_generated_files(cfg_files)
            if unexpected or duplicates:
                reasons["cfg_reason"] = "；".join(
                    (
                        [
                            "Forbidden file:"
                            + ", ".join(unexpected)
                        ]
                        if unexpected
                        else []
                    )
                    + (
                        [
                            "Duplicate file:"
                            + ", ".join(duplicates)
                        ]
                        if duplicates
                        else []
                    )
                )

        (
            status,
            validation_reasons,
            stage,
            details,
        ) = validate_current(stage1_values)
        reasons = validation_reasons

        if stage != "success":
            error_index += 1
            save_error(
                error_index,
                stage,
                details,
            )

        while (
            stage != "success"
            and int(result["repair_rounds"])
            < MAX_REPAIR_ROUNDS
        ):
            if (
                discover_tla_files()
                and not cfg_initial_called
            ):
                response, usage = call_model(
                    client,
                    build_cfg_prompt(reference_bundle),
                    "You are a strict TLC configuration engineer."
                    "Generate the only runnable Cassandra.cfg based on the current Cassandra TLA+ file.",
                )
                add_usage(result, usage)
                result["initial_cfg_calls"] = 1
                cfg_initial_called = True

                cfg_files, unexpected, duplicates = (
                    extract_generated_files(
                        response,
                        allow_cfg=True,
                    )
                )
                save_generated_files(cfg_files)

                (
                    status,
                    validation_reasons,
                    stage,
                    details,
                ) = validate_current(stage1_values)
                reasons = validation_reasons

                if stage != "success":
                    error_index += 1
                    save_error(
                        error_index,
                        stage,
                        details,
                    )
                continue

            result["repair_rounds"] = (
                int(result["repair_rounds"]) + 1
            )
            round_no = int(result["repair_rounds"])

            print(
                f"T2/{repeat_index:02d} incremental repair "
                f"{round_no}/{MAX_REPAIR_ROUNDS}，"
                f"current issue={stage}"
            )

            response, usage = call_model(
                client,
                build_repair_prompt(stage, details),
                "You are a strict TLA+ incremental repair engineer."
                "Only handle current file structure, cfg, SANY or TLC errors;"
                "Do not modify code based on the final hard check result.",
            )
            add_usage(result, usage)

            applied, apply_message = (
                apply_repair_response(response)
            )
            if not applied:
                stage = "api_or_repair"
                details = apply_message
                reasons["api_reason"] = apply_message
                error_index += 1
                save_error(
                    error_index,
                    stage,
                    details,
                )
                continue

            if (
                discover_tla_files()
                and not cfg_initial_called
            ):
                response, usage = call_model(
                    client,
                    build_cfg_prompt(reference_bundle),
                    "You are a strict TLC configuration engineer."
                    "Generate the only runnable Cassandra.cfg based on the current Cassandra TLA+ file.",
                )
                add_usage(result, usage)
                result["initial_cfg_calls"] = 1
                cfg_initial_called = True

                cfg_files, _, _ = (
                    extract_generated_files(
                        response,
                        allow_cfg=True,
                    )
                )
                save_generated_files(cfg_files)

            (
                status,
                validation_reasons,
                stage,
                details,
            ) = validate_current(stage1_values)
            reasons = validation_reasons

            if stage != "success":
                error_index += 1
                save_error(
                    error_index,
                    stage,
                    details,
                )

        if stage == "success":
            result["stop_reason"] = (
                "execution_success"
            )
            print(
                f"T2/{repeat_index:02d} passed"
                "file/cfg, SANY and TLC, stop repair."
            )
        elif (
            int(result["repair_rounds"])
            >= MAX_REPAIR_ROUNDS
        ):
            result["stop_reason"] = "repair_limit"
            print(
                f"Reached maximum repair rounds "
                f"{MAX_REPAIR_ROUNDS}, stop repair."
            )
        else:
            result["stop_reason"] = stage

    except Exception as exc:
        reasons["api_reason"] = (
            str(exc).splitlines()[0][:500]
        )
        result["stop_reason"] = "pipeline_error"
        error_index += 1
        save_error(
            error_index,
            "pipeline",
            str(exc),
        )
        print(
            f"T2/{repeat_index:02d} "
            f"pipeline exception: {exc}"
        )

    finally:
        # The final hard check only evaluates; it does not provide feedback or modify code.
        evaluate_final_hard_check(
            status,
            reasons,
        )
        result["finished_at"] = now_text()
        update_dynamic_metadata(result)
        print_summary(status, reasons)
        write_result(result, status, reasons)

        print(f"result file: {RESULT_PATH}")
        if HARD_CHECK_LOG_PATH.is_file():
            print(
                "Hard check failed, report:"
                f"{HARD_CHECK_LOG_PATH}"
            )
        else:
            print(
                "Hard checks passed; no additional report generated."
            )
        if TLC_LOG_PATH.is_file():
            print(
                f"TLC passed output: {TLC_LOG_PATH}"
            )

        error_files = (
            sorted(
                ERROR_DIR.glob(
                    "err[0-9][0-9]_*.txt"
                )
            )
            if ERROR_DIR.is_dir()
            else []
        )
        if error_files:
            print(
                f"Failure records: total {len(error_files)},"
                f"located in {ERROR_DIR}"
            )

    return result

def main() -> int:
    qdrant_spec, qdrant_helper = validate_inputs()
    result = run_one_experiment(
        qdrant_spec,
        qdrant_helper,
    )
    print(
        "\n=== Cassandra T2 experiment completed ==="
    )
    print(
        f"T2/"
        f"{int(result.get('repeat_index', 0)):02d}: recorded"
    )
    return 0

